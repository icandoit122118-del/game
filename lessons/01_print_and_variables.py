# =============================================
# 1강. 출력(print)과 변수(variable)
# 실행 방법: python3 01_print_and_variables.py
# =============================================

# '#'으로 시작하는 줄은 "주석"입니다. 컴퓨터는 무시하고, 사람만 읽어요.

# --- 1. 화면에 글자 출력하기 ---
print("안녕하세요!")          # 따옴표 안의 글자를 그대로 출력
print("프로그래밍", "시작!")  # 쉼표로 여러 개를 이어서 출력 (사이에 공백)

# --- 2. 변수: 값을 담아두는 "이름표 붙은 상자" ---
name = "철수"     # 문자열(str): 따옴표로 감싼 글자
age = 12          # 정수(int): 소수점 없는 숫자
height = 150.5    # 실수(float): 소수점 있는 숫자
is_student = True # 불리언(bool): True(참) 또는 False(거짓)

print(name, age, height, is_student)

# --- 3. 변수 값은 바꿀 수 있어요 ---
age = age + 1     # 오른쪽을 먼저 계산 → 13을 다시 age에 저장
print("내년 나이:", age)

# --- 4. 계산하기 ---
print(7 + 3)   # 더하기 10
print(7 - 3)   # 빼기 4
print(7 * 3)   # 곱하기 21
print(7 / 3)   # 나누기 2.333...
print(7 // 3)  # 몫 2
print(7 % 3)   # 나머지 1
print(2 ** 3)  # 거듭제곱 8

# --- 5. f-string: 문장 안에 변수 끼워 넣기 ---
print(f"{name}의 나이는 {age}살이고, 키는 {height}cm입니다.")

