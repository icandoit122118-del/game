# --- 1. 사용자에게 입력 받기 ---
name = input("이름이 뭐예요? ")   # 키보드로 입력한 글자가 name에 저장됨
print(f"반가워요, {name}님!")

# --- 2. input()은 항상 "문자열"을 돌려줘요 ---
text = input("좋아하는 숫자를 입력하세요: ")
print(type(text))   # <class 'str'>  ← 숫자처럼 보여도 문자열!

# 문자열끼리 +를 하면 "이어 붙이기"가 됩니다.
print(text + text)  # "7" + "7" → "77"

# --- 3. 숫자로 바꾸기(형 변환) ---
number = int(text)  # 문자열 → 정수
print(number + number)  # 7 + 7 → 14

# 자주 쓰는 변환 함수
# int("10")   → 10     (정수로)
# float("3.5")→ 3.5    (실수로)
# str(10)     → "10"   (문자열로)

# --- 4. 간단한 계산기 ---
a = float(input("첫 번째 숫자: "))
b = float(input("두 번째 숫자: "))
print(f"{a} + {b} = {a + b}")
print(f"{a} x {b} = {a * b}")

