# =============================================
# 5강. 리스트(list): 여러 값을 한 번에 담기
# 실행 방법: python3 05_lists.py
# =============================================

# --- 1. 리스트 만들기 ---
fruits = ["사과", "바나나", "포도"]
print(fruits)

# --- 2. 인덱스(index)로 꺼내기: 0부터 시작! ---
print(fruits[0])    # 사과  (첫 번째)
print(fruits[2])    # 포도  (세 번째)
print(fruits[-1])   # 포도  (-1은 맨 마지막)

# --- 3. 추가 / 수정 / 삭제 ---
fruits.append("딸기")      # 맨 뒤에 추가
fruits[1] = "망고"         # 두 번째 값을 바꾸기
fruits.remove("사과")      # 값으로 삭제
print(fruits)              # ['망고', '포도', '딸기']
print("개수:", len(fruits)) # len()은 길이(개수)

# --- 4. for와 함께 쓰기 ---
for fruit in fruits:
    print(f"나는 {fruit}를 좋아해요")

# --- 5. 포함 여부 확인: in ---
if "포도" in fruits:
    print("포도가 있어요!")

# --- 6. 숫자 리스트 활용 ---
scores = [85, 92, 78, 95, 88]
print("최고 점수:", max(scores))
print("최저 점수:", min(scores))
print("평균:", sum(scores) / len(scores))

