# --- 1. 비교 연산자: 결과는 True 또는 False ---
print(5 > 3)    # True   크다
print(5 < 3)    # False  작다
print(5 >= 5)   # True   크거나 같다
print(5 == 5)   # True   같다   (=는 "저장", ==는 "비교"!)
print(5 != 3)   # True   다르다

# --- 2. if: 조건이 참일 때만 실행 ---
score = int(input("점수를 입력하세요 (0~100): "))

# 콜론(:) 다음 줄은 반드시 "들여쓰기"(스페이스 4칸)를 해야 해요.
# 들여쓴 부분이 if에 속한 코드 묶음(블록)입니다.
if score >= 90:
    print("A 학점")
elif score >= 80:     # 위 조건이 거짓일 때 다음 조건 검사
    print("B 학점")
elif score >= 70:
    print("C 학점")
else:                 # 모든 조건이 거짓일 때
    print("다음엔 더 잘할 수 있어요!")

# --- 3. 논리 연산자: and, or, not ---
age = int(input("나이를 입력하세요: "))
has_ticket = input("표가 있나요? (y/n): ") == "y"

if age >= 12 and has_ticket:
    print("입장 가능합니다.")
elif not has_ticket:
    print("표를 먼저 사 주세요.")
else:
    print("12세 이상만 입장할 수 있어요.")

