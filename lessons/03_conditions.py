# 스카이림 플러그인 종류
#   .esm : 마스터 파일. 다른 모드들이 기대는 "기반" 파일 (Skyrim.esm 등)
#   .esp : 일반 플러그인. 대부분의 모드
#   .esl : 라이트 플러그인. 254개 제한에 포함되지 않음!

filename = input("플러그인 파일 이름: ").strip()
ext = filename.lower()[-4:]

# --- 1. if / elif / else ---
# 콜론(:) 다음 줄은 반드시 들여쓰기(스페이스 4칸)! 들여쓴 부분이 그 조건에 속해요.
if ext == ".esm":                # == 는 "같은가?" 비교 (= 는 저장)
    print("마스터 파일이에요. 로드 순서 위쪽에 와요.")
elif ext == ".esl":
    print("라이트 플러그인이에요. 254개 제한에 포함되지 않아요.")
elif ext == ".esp":
    print("일반 플러그인이에요.")
else:
    print("스카이림 플러그인이 아니에요.")

# --- 2. 비교 연산자: >, <, >=, <=, ==, != ---
count = int(input("켜 둔 일반 플러그인 개수: "))
if count > 254:
    print("[오류] 254개를 넘으면 게임이 제대로 동작하지 않아요!")
elif count >= 240:
    print("[경고] 한도에 가까워요. .esl 로 바꿀 수 있는 모드를 찾아보세요.")
else:
    print("[OK] 여유 있어요.")

# --- 3. and / or / not ---
is_patch = "patch" in filename.lower()
is_plugin = ext in (".esm", ".esp", ".esl")

if is_plugin and is_patch:
    print("호환 패치예요. 패치 대상 모드들보다 뒤에 로드해야 해요.")
if not is_plugin:
    print("플러그인이 아니라 텍스처/메시 같은 에셋 파일일 수도 있어요.")

