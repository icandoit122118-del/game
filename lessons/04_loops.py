# --- 1. for: 정해진 횟수만큼 반복 ---
# range(5)는 0, 1, 2, 3, 4 를 차례로 만들어 줘요. (5는 포함 안 됨!)
for i in range(5):
    print("반복", i)

# range(시작, 끝) : 1부터 10까지
total = 0
for n in range(1, 11):
    total = total + n
print("1부터 10까지의 합:", total)  # 55

# --- 2. 구구단 2단 ---
for n in range(1, 10):
    print(f"2 x {n} = {2 * n}")

# --- 3. while: 조건이 참인 동안 계속 반복 ---
count = 3
while count > 0:
    print(f"{count}...")
    count = count - 1   # 이 줄이 없으면 영원히 끝나지 않아요(무한 루프)!
print("발사! 🚀")

# --- 4. break: 반복을 즉시 멈추기 ---
while True:  # 일부러 무한 반복을 만들고
    answer = input("'그만'을 입력하면 끝나요: ")
    if answer == "그만":
        break    # 여기서 반복 탈출
    print(f"'{answer}'라고 입력했네요.")

